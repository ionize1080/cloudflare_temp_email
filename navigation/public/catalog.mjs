const normalize = value => value.toLocaleLowerCase().trim().replace(/^https?:\/\//,'').replace(/^www\./,'').replace(/\/$/,'');
export function suggestWebsites(query, limit = 6) {
 const q=normalize(query);
 if(!q)return websites.slice(0,limit);
 return websites.map((site,index)=>{
  const name=normalize(site.name),address=normalize(site.url),aliases=site.aliases.toLocaleLowerCase().split(/\s+/),companies=site.company.toLocaleLowerCase().split(/\s+/);
  let score=0;
  if(name===q||address===q)score=220;
  else if(aliases.includes(q))score=200;
  else if(companies.includes(q))score=150;
  else if(name.startsWith(q)||address.startsWith(q))score=130;
  else if(aliases.some(a=>a.startsWith(q)))score=110;
  else if(name.includes(q)||address.includes(q)||site.aliases.toLocaleLowerCase().includes(q))score=80;
  else if(site.company.toLocaleLowerCase().includes(q))score=40;
  return {site,score,index};
 }).filter(r=>r.score).sort((a,b)=>b.score-a.score||a.index-b.index).slice(0,limit).map(r=>r.site);
}
